"""Grid runner: strategy x problem, with resumable records and per-run traces.

Layout written under ``run_dir/run_id/``:

- ``config.json``   the exact settings used (so a run is reproducible),
- ``records.jsonl`` one :class:`~reasoning_lab.evaluation.metrics.EvalRecord` per job,
  appended as each job finishes and used as the resume checkpoint,
- ``traces.jsonl``  one full search tree per job, for the UI replay and offline rerank,
- ``report.md``     generated by :mod:`reasoning_lab.evaluation.report`.
"""

from __future__ import annotations

import asyncio
import json
import time
from collections.abc import Callable, Sequence
from dataclasses import asdict, dataclass, field, replace
from pathlib import Path
from typing import Any

from ..llm.base import LLMClient, LLMError
from ..schema import Problem, ReasoningTree, RunMetrics, ScoreCard, StrategyOutput, VerifyStatus
from ..strategies import run_strategy
from ..strategies.base import BudgetExhausted, SearchConfig
from ..verification.prm import build_prm
from ..verification.prm.base import Aggregator, ProcessRewardModel
from .metrics import EvalRecord, record_from_output

JsonDict = dict[str, Any]


@dataclass
class GridJob:
    strategy: str
    problem: Problem
    seed: int
    prm: str
    aggregator: Aggregator = "geomean"

    @property
    def key(self) -> str:
        return f"{self.strategy}|{self.problem.id}|seed{self.seed}|{self.prm}|{self.aggregator}"


@dataclass
class GridSpec:
    strategies: tuple[str, ...] = ("cot", "self_consistency", "best_of_n", "tot", "mcts")
    prm: str = "symbolic"
    #: how per-step scores become a path score; see ProcessRewardModel.path_value
    prm_aggregator: Aggregator = "geomean"
    prm_model: Path | str | None = None
    seeds: tuple[int, ...] = (0,)
    concurrency: int = 2
    save_traces: bool = True
    resume: bool = True

    def config_dict(self) -> JsonDict:
        return asdict(self)


@dataclass
class RunResult:
    run_id: str
    directory: Path
    records: list[EvalRecord] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)
    skipped: int = 0

    @property
    def succeeded(self) -> int:
        return sum(1 for r in self.records if not r.error)


def default_run_id(*, prefix: str = "run") -> str:
    return f"{prefix}-{time.strftime('%Y%m%d-%H%M%S')}"


def _read_records(path: Path) -> tuple[dict[str, EvalRecord], set[str]]:
    """Read the checkpoint; the latest record per job key wins.

    A job whose latest record carries an ``error`` is left out of the done set so
    the next pass retries it — a transient API failure should not poison a run.
    """
    if not path.is_file():
        return {}, set()
    latest: dict[str, EvalRecord] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            payload = json.loads(line)
            record = EvalRecord.model_validate(payload)
        except Exception as exc:
            print(f"[runner] skipping unreadable record line: {exc}")
            continue
        key = str(payload.get("key") or f"{record.card.strategy}|{record.card.problem_id}")
        latest[key] = record
    done = {key for key, record in latest.items() if not record.error}
    return latest, done


class _AppendLog:
    """Line-append helper that survives concurrent tasks and partial writes."""

    def __init__(self, path: Path) -> None:
        self.path = path
        self.lock = asyncio.Lock()
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file():
            path.touch()

    async def write(self, payload: JsonDict) -> None:
        line = json.dumps(payload, ensure_ascii=False, default=str)
        async with self.lock:
            with self.path.open("a", encoding="utf-8") as handle:
                handle.write(line + "\n")
                handle.flush()


async def _one_job(
    job: GridJob,
    *,
    llm: LLMClient,
    config: SearchConfig,
    prm_factory: Callable[[Problem], ProcessRewardModel] | None,
    prm_model: Path | str | None = None,
) -> tuple[EvalRecord, ReasoningTree | None]:
    started = time.perf_counter()
    job_config = replace(config, seed=job.seed)
    prm = (
        prm_factory(job.problem)
        if prm_factory
        else build_prm(job.prm, model_path=prm_model, aggregator=job.aggregator)
    )
    try:
        output: StrategyOutput = await run_strategy(job.strategy, job.problem, llm, prm, job_config)
    except (BudgetExhausted, LLMError, RuntimeError, ValueError, KeyError) as exc:
        latency = (time.perf_counter() - started) * 1000.0
        record = _failed_record(job, latency, f"{type(exc).__name__}: {exc}")
        return record, None
    latency = (time.perf_counter() - started) * 1000.0
    output.tree.metrics.wall_time_s += latency / 1000.0
    record = record_from_output(job.problem, output, latency_ms=latency)
    return record, output.tree


def _failed_record(job: GridJob, latency_ms: float, error: str) -> EvalRecord:
    card = ScoreCard(
        problem_id=job.problem.id,
        strategy=job.strategy,
        subject=job.problem.subject,
        level=job.problem.level,
        gold=job.problem.answer,
        latency_ms=latency_ms,
        verify_status=VerifyStatus.NOT_CHECKED,
        metrics=RunMetrics(),
        notes="",
    )
    return EvalRecord(card=card, error=error)


async def run_grid(
    problems: Sequence[Problem],
    *,
    llm: LLMClient,
    config: SearchConfig | None = None,
    spec: GridSpec | None = None,
    run_dir: Path | str = "runs",
    run_id: str | None = None,
    prm_factory: Callable[[Problem], ProcessRewardModel] | None = None,
    on_progress: Callable[[str, EvalRecord], None] | None = None,
) -> RunResult:
    """Run every (strategy, seed, problem) job, appending results as they land."""
    spec = spec or GridSpec()
    config = config or SearchConfig()
    directory = Path(run_dir) / (run_id or default_run_id())
    directory.mkdir(parents=True, exist_ok=True)
    records_path = directory / "records.jsonl"
    traces_path = directory / "traces.jsonl"

    (directory / "config.json").write_text(
        json.dumps(
            {"run_id": directory.name, "grid": spec.config_dict(), "search": asdict(config),
             "problems": [p.id for p in problems]},
            indent=2,
            ensure_ascii=False,
            default=str,
        ),
        encoding="utf-8",
    )

    loaded, done_keys = (_read_records(records_path) if spec.resume else ({}, set()))
    jobs = [
        GridJob(
            strategy=strategy,
            problem=problem,
            seed=seed,
            prm=spec.prm,
            aggregator=spec.prm_aggregator,
        )
        for strategy in spec.strategies
        for seed in spec.seeds
        for problem in problems
    ]
    pending = [job for job in jobs if job.key not in done_keys]
    by_key = dict(loaded)
    result = RunResult(
        run_id=directory.name,
        directory=directory,
        records=list(by_key.values()),
        skipped=len(jobs) - len(pending),
    )

    records_log = _AppendLog(records_path)
    traces_log = _AppendLog(traces_path)
    semaphore = asyncio.Semaphore(max(1, spec.concurrency))

    async def worker(job: GridJob) -> None:
        async with semaphore:
            record, tree = await _one_job(
                job, llm=llm, config=config, prm_factory=prm_factory, prm_model=spec.prm_model
            )
            payload = record.model_dump()
            payload["seed"] = job.seed
            payload["prm"] = job.prm
            payload["prm_aggregator"] = job.aggregator
            payload["key"] = job.key
            await records_log.write(payload)
            if spec.save_traces and tree is not None:
                await traces_log.write(
                    {"key": job.key, "problem_id": job.problem.id, "seed": job.seed, "tree": tree.model_dump()}
                )
            by_key[job.key] = record
            if record.error:
                result.errors.append(f"{job.key}: {record.error}")
            if on_progress:
                on_progress(job.key, record)

    await asyncio.gather(*(worker(job) for job in pending))
    result.records = sorted(by_key.values(), key=lambda r: (r.card.strategy, r.card.problem_id))
    return result


__all__ = ["GridJob", "GridSpec", "RunResult", "default_run_id", "run_grid"]
